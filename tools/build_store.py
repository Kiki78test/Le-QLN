def rendre(pg, contenu, sortie, w, h, dpr):
    pg.set_viewport_size({"width": w, "height": h})
    pg.set_content(contenu); pg.evaluate("document.fonts.ready.then(() => window.ajuster && ajuster())"); pg.wait_for_timeout(120)
    pg.screenshot(path=str(sortie), type="png" if sortie.suffix == ".png" else "jpeg", **({} if sortie.suffix == ".png" else {"quality": 90}))


def main():
    with sync_playwright() as p:
        nav = p.chromium.launch()
        for lang in ["fr", "en"]:
            f = ST.fiche(lang, NOM); verifier(lang, f)
            d = STORE / lang; d.mkdir(parents=True, exist_ok=True)
            (d / "textes.md").write_text(textes_md(lang, f), encoding="utf-8")
            brutes = sorted((BRUTES / lang / "telephone").glob("*.png"))
            assert len(brutes) == len(ST.LEGENDES[lang]), f"{lang} : {len(brutes)} captures brutes (lancer node tools/store_captures.js)"
            for fmt, (w, h, dpr) in FORMATS.items():
                ctx = nav.new_context(device_scale_factor=dpr); pg = ctx.new_page()
                (d / fmt).mkdir(exist_ok=True)
                for brute, (scene, l1, l2) in zip(brutes, ST.LEGENDES[lang]):
                    assert scene in brute.name, (brute.name, scene)
                    rendre(pg, page_capture(w, h, l1, l2, img64(brute)), d / fmt / (brute.stem + ".jpg"), w, h, dpr)
                ctx.close()
            ctx = nav.new_context(device_scale_factor=1); pg = ctx.new_page()
            acc = "Le jeu d'anagrammes où l'on joue pour l'or" if lang == "fr" else "The anagram game where you play for gold"
            rendre(pg, page_banniere(lang, acc, [img64(brutes[2]), img64(brutes[1])]), d / "banniere-play-1024x500.png", 1024, 500, 1)
            ctx.close()
            print("store/" + lang)
        nav.close()
    from PIL import Image
    Image.open(RACINE / "icons" / "icon-512.png").convert("RGBA").resize((512, 512)).save(STORE / "icone-play-512.png")
    securite_md()
    pdf()


def securite_md():
    lignes = ["# Questionnaires des stores — " + NOM, "",
              "Réponses à reporter dans la Play Console (Contenu de l'appli) et App Store Connect (Confidentialité de l'app).",
              "Cohérentes avec la politique de confidentialité. Généré par `tools/build_store.py` — ne pas modifier ici.", "",
              "## Informations générales", "", "| Rubrique | Google Play | App Store |", "|---|---|---|"]
    lignes += [f"| {a} | {b} | {c} |" for a, b, c in ST.INFOS]
    lignes += ["", "## Google Play — Sécurité des données", ""] + [f"- **{q}** {r}" for q, r in ST.SECURITE_GENERAL]
    for phase, titre in [("maintenant", "Dès maintenant"), ("pub", "À ajouter le jour où AdMob est activé")]:
        lignes += ["", f"### {titre}", "", "| Type de données | Collecté | Partagé | Facultatif ? | Finalités |", "|---|---|---|---|---|"]
        lignes += [f"| {a} | {b} | {c} | {d} | {e} |" for a, b, c, d, e, ph in ST.SECURITE_DONNEES if ph == phase]
    lignes += ["", ST.NON_COLLECTE, "", "## App Store — Confidentialité de l'app", ""]
    for phase, titre in [("maintenant", "Dès maintenant"), ("pub", "À ajouter le jour où AdMob est activé (avec la fenêtre ATT)")]:
        lignes += [f"### {titre}", "", "| Donnée | Liée à l'identité | Suivi (tracking) | Finalités |", "|---|---|---|---|"]
        lignes += [f"| {a} | {b} | {c} | {d} |" for a, b, c, d, ph in ST.APPLE_DONNEES if ph == phase]
        lignes += [""]
    (STORE / "questionnaires.md").write_text("\n".join(lignes) + "\n", encoding="utf-8")


