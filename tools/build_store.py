def img64(p): return "data:image/png;base64," + base64.b64encode(p.read_bytes()).decode()


def verifier(lang, f):
    for cle, lim in ST.LIMITES.items():
        n = len(f[cle].replace("\n", "")) if cle != "longue" else len(f[cle])
        assert n <= lim, f"{lang} : « {cle} » fait {n} caractères (limite {lim})"
    assert all(" " not in m for m in f["mots_cles"].split(",")[0:0]), "mots-clés"


